def _escape_pdf(text: str) -> str:
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _write_resume_pdf(path, name: str, headline: str, skills: list[str], location: str) -> None:
    """Create a tiny valid one-page PDF so demo resume downloads actually work."""
    lines = [
        name,
        headline,
        location,
        "",
        "Skills: " + ", ".join(skills),
        "",
        "This is a sample resume generated by the TalentHub seed script.",
        "Upload a real PDF, DOC or DOCX from the candidate profile page.",
    ]
    parts = ["BT", "/F1 20 Tf", "72 740 Td", f"({_escape_pdf(lines[0])}) Tj"]
    parts += ["0 -30 Td", "/F1 12 Tf"]
    for line in lines[1:]:
        parts.append(f"({_escape_pdf(line)}) Tj")
        parts.append("0 -18 Td")
    parts.append("ET")
    stream = "\n".join(parts).encode("latin-1", "replace")

    objects = [
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        (
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
            "/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>"
        ),
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        f"<< /Length {len(stream)} >>\nstream\n" + stream.decode("latin-1") + "\nendstream",
    ]

    pdf = "%PDF-1.4\n"
    offsets: list[int] = []
    for index, obj in enumerate(objects, start=1):
        offsets.append(len(pdf.encode("latin-1")))
        pdf += f"{index} 0 obj\n{obj}\nendobj\n"
    xref_offset = len(pdf.encode("latin-1"))
    pdf += f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n"
    for offset in offsets:
        pdf += f"{offset:010d} 00000 n \n"
    pdf += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
        f"startxref\n{xref_offset}\n%%EOF\n"
    )
    path.write_bytes(pdf.encode("latin-1"))


def _attach_sample_resume(profile: CandidateProfile, filename: str, **kwargs) -> None:
    settings.resume_path.mkdir(parents=True, exist_ok=True)
    stored_name = f"seed_{profile.user_id}_{filename}"
    _write_resume_pdf(settings.resume_path / stored_name, **kwargs)
    profile.resume_filename = filename
    profile.resume_stored_name = stored_name
    profile.resume_uploaded_at = datetime.now(timezone.utc)


